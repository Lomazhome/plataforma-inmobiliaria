-- ============================================================
-- LoMaz Home — Sección «Formatos» del panel (formatos.html)
-- Qué crea:
--   1. La tabla public.formatos: la lista de formatos por proceso.
--   2. El depósito privado «formatos» en Storage: ahí viven los archivos.
--   3. Los permisos: solo usuarios activos del equipo (la misma regla
--      que usa Contactos). El público no ve ni descarga nada.
--   4. La lista inicial de formatos (sin archivos: se suben desde la página).
-- Se puede ejecutar más de una vez sin dañar nada.
-- ============================================================

create table if not exists public.formatos (
  id              bigint generated by default as identity primary key,
  proceso         text not null check (proceso in ('captacion','venta','arriendo','administracion','cobros')),
  orden           integer not null default 100,
  nombre          text not null,
  uso             text,
  tipo            text not null default 'archivo' check (tipo in ('archivo','herramienta')),
  enlace          text,            -- solo para tipo 'herramienta'
  enlace_texto    text,            -- texto del botón, p. ej. «Abrir herramienta»
  archivos        jsonb not null default '[]'::jsonb,  -- [{ruta,nombre,ext,tam,fecha}]
  activo          boolean not null default true,
  actualizado_en  timestamptz not null default now(),
  actualizado_por uuid
);

create unique index if not exists formatos_proceso_nombre_uq on public.formatos (proceso, nombre);

alter table public.formatos enable row level security;
revoke all on public.formatos from anon;
grant select, insert, update on public.formatos to authenticated;

drop policy if exists "formatos_equipo_leer"    on public.formatos;
drop policy if exists "formatos_equipo_crear"   on public.formatos;
drop policy if exists "formatos_equipo_cambiar" on public.formatos;
create policy "formatos_equipo_leer" on public.formatos
  for select to authenticated using (public.es_usuario_activo());
create policy "formatos_equipo_crear" on public.formatos
  for insert to authenticated with check (public.es_usuario_activo());
create policy "formatos_equipo_cambiar" on public.formatos
  for update to authenticated using (public.es_usuario_activo()) with check (public.es_usuario_activo());

-- ---------- Depósito privado de archivos ----------
insert into storage.buckets (id, name, public, file_size_limit)
values ('formatos', 'formatos', false, 10485760)
on conflict (id) do update set public = false, file_size_limit = 10485760;

drop policy if exists "formatos_archivos_leer"    on storage.objects;
drop policy if exists "formatos_archivos_subir"   on storage.objects;
drop policy if exists "formatos_archivos_cambiar" on storage.objects;
drop policy if exists "formatos_archivos_borrar"  on storage.objects;
create policy "formatos_archivos_leer" on storage.objects
  for select to authenticated using (bucket_id = 'formatos' and public.es_usuario_activo());
create policy "formatos_archivos_subir" on storage.objects
  for insert to authenticated with check (bucket_id = 'formatos' and public.es_usuario_activo());
create policy "formatos_archivos_cambiar" on storage.objects
  for update to authenticated using (bucket_id = 'formatos' and public.es_usuario_activo())
  with check (bucket_id = 'formatos' and public.es_usuario_activo());
create policy "formatos_archivos_borrar" on storage.objects
  for delete to authenticated using (bucket_id = 'formatos' and public.es_usuario_activo());

